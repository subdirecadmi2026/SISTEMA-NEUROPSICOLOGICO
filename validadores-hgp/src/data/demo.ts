import type { Dataset } from "../types";
import { makeRowKey, validateEgresos } from "../lib/validateEgresos";
import { validateEmergencia } from "../lib/validateEmergencia";

const HOSPITAL = "Hospital General Puyo";

function egreso(
  rowNumber: number,
  values: Record<string, string>,
): Dataset["rows"][number] {
  return {
    rowNumber,
    rowKey: makeRowKey("egresos", values, String(rowNumber)),
    values: {
      historiaClinica: "",
      cedula: "",
      apellidosNombres: "",
      sexo: "",
      fechaNacimiento: "",
      edad: "",
      fechaIngreso: "",
      fechaEgreso: "",
      diasEstada: "",
      especialidad: "",
      servicio: "",
      diagnosticoPrincipal: "",
      diagnosticosSecundarios: "",
      condicionEgreso: "",
      tipoEgreso: "",
      procedimiento: "",
      medico: "",
      establecimiento: HOSPITAL,
      ...values,
    },
  };
}

function emergencia(
  rowNumber: number,
  values: Record<string, string>,
): Dataset["rows"][number] {
  return {
    rowNumber,
    rowKey: makeRowKey("emergencia", values, String(rowNumber)),
    values: {
      historiaClinica: "",
      cedula: "",
      apellidosNombres: "",
      sexo: "",
      edad: "",
      fechaHoraLlegada: "",
      fechaHoraAtencion: "",
      fechaHoraSalida: "",
      triage: "",
      motivoConsulta: "",
      diagnostico: "",
      condicionSalida: "",
      destino: "",
      especialidad: "",
      medico: "",
      establecimiento: HOSPITAL,
      ...values,
    },
  };
}

